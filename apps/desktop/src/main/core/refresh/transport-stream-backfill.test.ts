import type { SaveFile } from "@pond/schema/db";
import { describe, expect, it } from "vitest";
import {
  removeMisclassifiedTextDescription,
  repairTransportStreamFile,
} from "./transport-stream-backfill";

const file: SaveFile = {
  kind: "text_file",
  path: "sample.ts",
  sha256: "hash",
  size: 564,
  mimeType: "text/typescript",
};

function transportStreamHeader(): Buffer {
  const header = Buffer.alloc(188 * 3);
  header[0] = 0x47;
  header[188] = 0x47;
  header[376] = 0x47;
  return header;
}

describe("transport stream backfill", () => {
  it("repairs only .ts files with an MPEG transport-stream header", () => {
    expect(repairTransportStreamFile(file, transportStreamHeader())).toEqual({
      ...file,
      kind: "video",
      mimeType: "video/mp2t",
    });
    expect(
      repairTransportStreamFile(file, Buffer.from("export const value = 1;")),
    ).toBeNull();
    expect(
      repairTransportStreamFile(
        { ...file, path: "sample.txt" },
        transportStreamHeader(),
      ),
    ).toBeNull();
  });

  it("removes only the binary text body generated by the bad import", () => {
    const body = Buffer.from("\u0000binary video\n");
    expect(
      removeMisclassifiedTextDescription("\u0000binary video", body),
    ).toBeNull();
    expect(removeMisclassifiedTextDescription("My note", body)).toBe("My note");
  });
});
