import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(
  root,
  "src/main/core/refresh/harvest/lib/browser-validation-source.ts",
);
const result = await build({
  configFile: false,
  logLevel: "silent",
  root,
  build: {
    write: false,
    minify: true,
    lib: {
      entry: resolve(
        root,
        "src/main/core/refresh/harvest/lib/browser-validation.ts",
      ),
      name: "PondHarvestValidation",
      formats: ["iife"],
    },
  },
});
const buildResult = Array.isArray(result) ? result[0] : result;
const chunk = buildResult.output.find((item) => item.type === "chunk");
if (!chunk) throw new Error("Browser validation bundle was not generated");
const unformatted = `// Generated by scripts/generate-harvest-validation.mjs.\nexport const browserValidationSource =\n  ${JSON.stringify(chunk.code)};\n`;
const source = execFileSync(
  process.execPath,
  [
    resolve(root, "../../node_modules/@biomejs/biome/bin/biome"),
    "format",
    "--stdin-file-path",
    outputPath,
  ],
  { input: unformatted, encoding: "utf8" },
);
if (process.argv.includes("--check")) {
  if ((await readFile(outputPath, "utf8")) !== source)
    throw new Error(
      "Browser validation bundle is stale; run pnpm generate:harvest",
    );
} else {
  await writeFile(outputPath, source);
}
