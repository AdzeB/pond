import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Vendors AI provider brand marks from models.dev as currentColor React
// components (the same local-brand pattern as social-media/custom). Run with
// `pnpm --filter @pond/icons generate:providers`.
const here = dirname(fileURLToPath(import.meta.url));

// Our id -> models.dev logo id (mostly identical; Together differs).
const PROVIDERS: Record<string, { logo: string; label: string }> = {
  openai: { logo: "openai", label: "OpenAI" },
  anthropic: { logo: "anthropic", label: "Anthropic" },
  google: { logo: "google", label: "Google" },
  groq: { logo: "groq", label: "Groq" },
  mistral: { logo: "mistral", label: "Mistral" },
  xai: { logo: "xai", label: "xAI" },
  deepseek: { logo: "deepseek", label: "DeepSeek" },
  openrouter: { logo: "openrouter", label: "OpenRouter" },
  together: { logo: "togetherai", label: "Together" },
  perplexity: { logo: "perplexity", label: "Perplexity" },
  ollama: { logo: "ollama", label: "Ollama" },
  lmstudio: { logo: "lmstudio", label: "LM Studio" },
};

const ATTR_MAP: Record<string, string> = {
  "fill-rule": "fillRule",
  "clip-rule": "clipRule",
  "fill-opacity": "fillOpacity",
  "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
  "stroke-miterlimit": "strokeMiterlimit",
  "stroke-opacity": "strokeOpacity",
  "stroke-dasharray": "strokeDasharray",
  "shape-rendering": "shapeRendering",
  "clip-path": "clipPath",
  "stop-color": "stopColor",
  "stop-opacity": "stopOpacity",
};

function toJsxAttrs(svg: string): string {
  let out = svg;
  for (const [from, to] of Object.entries(ATTR_MAP)) {
    out = out.replaceAll(`${from}=`, `${to}=`);
  }
  return out;
}

function pascal(id: string): string {
  return id
    .split(/[-_]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
}

const exports: string[] = [];

for (const [id, { logo, label }] of Object.entries(PROVIDERS)) {
  const res = await fetch(`https://models.dev/logos/${logo}.svg`);
  if (!res.ok) throw new Error(`logo fetch failed for ${logo}: ${res.status}`);
  const raw = (await res.text()).trim();

  const rootTag = raw.match(/<svg[^>]*>/)?.[0] ?? "";
  const viewBox =
    rootTag.match(/viewBox="([^"]+)"/)?.[1] ??
    (() => {
      const w = rootTag.match(/\bwidth="([^"]+)"/)?.[1] ?? "24";
      const h = rootTag.match(/\bheight="([^"]+)"/)?.[1] ?? "24";
      return `0 0 ${w} ${h}`;
    })();
  // Outline marks set fill="none" and stroke the path; solid marks let paths
  // carry their own fill. Preserve the root value so we don't fill outlines.
  const rootFill = rootTag.match(/\bfill="([^"]+)"/)?.[1] ?? "currentColor";

  const inner = toJsxAttrs(
    raw
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<\/svg>\s*$/, "")
      .trim(),
  );

  const name = `IconProvider${pascal(id)}`;
  const component = `import type { SVGProps } from "react";

export function ${name}(props: SVGProps<SVGSVGElement>) {
  return (
    <svg
      viewBox="${viewBox}"
      fill="${rootFill}"
      xmlns="http://www.w3.org/2000/svg"
      role="img"
      aria-label="${label}"
      {...props}
    >
      <title>${label}</title>
      ${inner}
    </svg>
  );
}
`;
  writeFileSync(join(here, `${id}.tsx`), component);
  exports.push(`export * from "./${id}";`);
}

writeFileSync(
  join(here, "index.ts"),
  `// Generated by \`pnpm --filter @pond/icons generate:providers\`. Do not edit by hand.\n${exports.join("\n")}\n`,
);
console.log(`wrote ${Object.keys(PROVIDERS).length} provider logos`);
