import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateManifests } from "../src/settings/meta-schema";
import { SETTINGS_PREFS } from "../src/settings/prefs.manifest";
import { SETTINGS_SECTIONS_MANIFEST } from "../src/settings/sections.manifest";
import type {
  PrefsFieldSpec,
  PrefsFieldType,
  Row,
  SectionSpec,
  SlicePrefsSpec,
} from "../src/settings/types";

const HERE = dirname(fileURLToPath(import.meta.url));
const SCHEMA_SRC = resolve(HERE, "../src");
const SETTINGS_DIR = join(SCHEMA_SRC, "settings");
const REPO_ROOT = resolve(HERE, "../../..");
const DESKTOP_SETTINGS = resolve(
  HERE,
  "../../../apps/desktop/src/renderer/src/components/settings",
);

const BANNER = `// AUTOGENERATED by packages/schema/scripts/generate-settings.ts.
// Do not edit. Run \`pnpm -C packages/schema generate\` after editing the
// settings manifests (prefs.manifest.ts / sections.manifest.ts).
`;

// ----- value + type serialization -----

function tsKey(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

function tsValue(value: unknown): string {
  if (value === null) return "null";
  if (value === undefined) return "undefined";
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") {
    return String(value);
  }
  if (Array.isArray(value)) {
    return `[${value.map(tsValue).join(", ")}]`;
  }
  if (typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>).map(
      ([k, v]) => `${tsKey(k)}: ${tsValue(v)}`,
    );
    return `{ ${entries.join(", ")} }`;
  }
  return "null";
}

function literalType(value: string | number): string {
  return typeof value === "string" ? JSON.stringify(value) : String(value);
}

function fieldTsType(spec: PrefsFieldSpec): string {
  const type = spec.type;
  let base: string;
  if (type === "boolean" || type === "number" || type === "string") {
    base = type;
  } else if ("enum" in type) {
    base = type.enum.map(literalType).join(" | ");
  } else {
    base = type.ts;
  }
  return spec.nullable ? `${base} | null` : base;
}

function collectImports(): Map<string, Set<string>> {
  const byModule = new Map<string, Set<string>>();
  for (const slice of Object.values(SETTINGS_PREFS)) {
    if (slice.kind !== "fields") continue;
    for (const spec of Object.values(slice.fields)) {
      const type: PrefsFieldType = spec.type;
      if (typeof type === "object" && "ts" in type && type.import) {
        const set = byModule.get(type.import) ?? new Set<string>();
        set.add(type.ts);
        byModule.set(type.import, set);
      }
    }
  }
  return byModule;
}

// ----- prefs.generated.ts -----

function generatePrefs(): string {
  const importLines = [...collectImports().entries()]
    .map(([module, names]) => {
      const sorted = [...names].sort().join(", ");
      return `import type { ${sorted} } from ${JSON.stringify(module)};`;
    })
    .sort()
    .join("\n");

  const sliceTypes = Object.entries(SETTINGS_PREFS)
    .map(([slice, spec]) => {
      const fields = (spec as Extract<SlicePrefsSpec, { kind: "fields" }>)
        .fields;
      const lines = Object.entries(fields)
        .map(([key, f]) => `    ${tsKey(key)}: ${fieldTsType(f)};`)
        .join("\n");
      return `  ${tsKey(slice)}: {\n${lines}\n  };`;
    })
    .join("\n");

  const defaultValue: Record<string, Record<string, unknown>> = {};
  for (const [slice, spec] of Object.entries(SETTINGS_PREFS)) {
    const fields = (spec as Extract<SlicePrefsSpec, { kind: "fields" }>).fields;
    const out: Record<string, unknown> = {};
    for (const [key, f] of Object.entries(fields)) out[key] = f.default;
    defaultValue[slice] = out;
  }

  return `${BANNER}${importLines}\n\nexport interface Prefs {\n${sliceTypes}\n}\n\nexport const DEFAULT_PREFS: Prefs = ${tsValue(defaultValue)};\n`;
}

// ----- nav.generated.ts -----

function generateNav(): string {
  const sections = SETTINGS_SECTIONS_MANIFEST.map(
    (s) =>
      `  { id: ${JSON.stringify(s.id)}, path: ${JSON.stringify(s.id)}, label: ${JSON.stringify(s.label)}, group: ${JSON.stringify(s.group)} },`,
  ).join("\n");

  const devGroups = [...new Set(SETTINGS_SECTIONS_MANIFEST.map((s) => s.group))]
    .filter((g) => g === "dev")
    .map((g) => JSON.stringify(g))
    .join(", ");

  const icons = SETTINGS_SECTIONS_MANIFEST.map(
    (s) => `  ${tsKey(s.id)}: ${JSON.stringify(s.icon)},`,
  ).join("\n");

  return `${BANNER}import type { SettingsGroup, SettingsSection } from "../settings";\n\nexport const SETTINGS_SECTIONS: readonly SettingsSection[] = [\n${sections}\n] as const;\n\nexport const SETTINGS_DEV_GROUPS: readonly SettingsGroup[] = [${devGroups}] as const;\n\nexport const SETTINGS_SECTION_ICONS: Record<string, string> = {\n${icons}\n};\n`;
}

// ----- validator.generated.ts -----

function zodField(slice: string, key: string, spec: PrefsFieldSpec): string {
  const ref = `DEFAULT_PREFS.${tsKey(slice)}.${tsKey(key)}`;
  const type = spec.type;

  if (type === "boolean") return `z.boolean().catch(${ref})`;
  if (type === "string") return `z.string().catch(${ref})`;
  if (type === "number") {
    let s = "z.number()";
    if (spec.min !== undefined) s += `.min(${spec.min})`;
    if (spec.max !== undefined) s += `.max(${spec.max})`;
    if (spec.nullable) s += ".nullable()";
    return `${s}.catch(${ref})`;
  }
  if ("enum" in type) {
    const allStrings = type.enum.every((v) => typeof v === "string");
    let s: string;
    if (allStrings) {
      s = `z.enum([${type.enum.map((v) => JSON.stringify(v)).join(", ")}])`;
    } else {
      const parts = type.enum
        .map((v) => `z.literal(${literalType(v)})`)
        .join(", ");
      s = `z.union([${parts}])`;
    }
    if (spec.nullable) s += ".nullable()";
    return `${s}.catch(${ref})`;
  }
  // Reference type: validated loosely, defaulted when absent.
  return `z.any().default(${ref})`;
}

function generateValidator(): string {
  const slices = Object.entries(SETTINGS_PREFS)
    .map(([slice, spec]) => {
      const fields = (spec as Extract<SlicePrefsSpec, { kind: "fields" }>)
        .fields;
      const lines = Object.entries(fields)
        .map(([key, f]) => `    ${tsKey(key)}: ${zodField(slice, key, f)},`)
        .join("\n");
      return `  ${tsKey(slice)}: z\n    .object({\n${lines}\n    })\n    .catch(DEFAULT_PREFS.${tsKey(slice)}),`;
    })
    .join("\n");

  return `${BANNER}import { z } from "zod";\nimport { DEFAULT_PREFS } from "./prefs.generated";\n\nexport const PrefsSchema = z\n  .object({\n${slices}\n  })\n  .catch(DEFAULT_PREFS);\n\nexport type PrefsParsed = z.infer<typeof PrefsSchema>;\n`;
}

// ----- sections.generated.ts (desktop) -----

function emitField(row: Extract<Row, { control: ControlLike }>): string {
  const parts: string[] = [
    `control: ${JSON.stringify(row.control)}`,
    `key: ${JSON.stringify(row.key)}`,
  ];
  if (row.title) parts.push(`title: ${JSON.stringify(row.title)}`);
  if (row.description) {
    parts.push(`description: ${JSON.stringify(row.description)}`);
  }
  if (row.control === "select" && row.options) {
    parts.push(`options: ${tsValue(row.options)}`);
  }
  if (row.control === "range") {
    parts.push(`min: ${row.min}`, `max: ${row.max}`);
    if (row.step !== undefined) parts.push(`step: ${row.step}`);
    if (row.suffix) parts.push(`suffix: ${JSON.stringify(row.suffix)}`);
  }
  if (row.control === "stepper") {
    parts.push(`min: ${row.min}`, `max: ${row.max}`);
    if (row.step !== undefined) parts.push(`step: ${row.step}`);
    if (row.fallback !== undefined) parts.push(`fallback: ${row.fallback}`);
  }
  if (row.control === "number") {
    parts.push(`min: ${row.min}`, `max: ${row.max}`);
    if (row.unit) parts.push(`unit: ${JSON.stringify(row.unit)}`);
  }
  if (row.visible) parts.push(`visible: predicates.${row.visible}`);
  if (row.disabled) parts.push(`disabled: predicates.${row.disabled}`);
  if (row.apply)
    parts.push(`apply: () => runApply(${JSON.stringify(row.apply)})`);
  return `{ ${parts.join(", ")} }`;
}

type ControlLike =
  | "switch"
  | "select"
  | "range"
  | "stepper"
  | "number"
  | "color";

function emitItem(row: Row): string {
  if (row.control === "custom") {
    const parts = [
      `control: "custom"`,
      `key: ${JSON.stringify(row.key)}`,
      `render: (b) => createElement(components.${row.component}, { binding: b })`,
    ];
    if (row.visible) parts.push(`visible: predicates.${row.visible}`);
    return `{ ${parts.join(", ")} }`;
  }
  return emitField(row);
}

function emitSection(section: SectionSpec): string {
  if (section.custom) {
    return `{ component: sections.${section.custom} }`;
  }
  const parts: string[] = [`title: ${JSON.stringify(section.label)}`];
  if (section.description) {
    parts.push(`description: ${JSON.stringify(section.description)}`);
  }
  if (section.slice) parts.push(`prefsKey: ${JSON.stringify(section.slice)}`);

  const groups = (section.groups ?? []).map((group) => {
    const gParts: string[] = [];
    if (group.title) gParts.push(`title: ${JSON.stringify(group.title)}`);
    if (group.binding) {
      gParts.push(`useBinding: bindings[${JSON.stringify(group.binding)}]`);
    } else if (group.slice) {
      gParts.push(`prefsKey: ${JSON.stringify(group.slice)}`);
    }
    if (group.visible) gParts.push(`visible: predicates.${group.visible}`);
    if (group.items) {
      gParts.push(`items: [${group.items.map(emitItem).join(", ")}]`);
    }
    if (group.body) {
      gParts.push(
        `render: (b) => createElement(components.${group.body}, { binding: b })`,
      );
    }
    return `{ ${gParts.join(", ")} }`;
  });

  parts.push(`groups: [${groups.join(", ")}]`);
  return `{ ${parts.join(", ")} }`;
}

function generateSections(): string {
  const entries = SETTINGS_SECTIONS_MANIFEST.map(
    (section) => `  ${tsKey(section.id)}: ${emitSection(section)},`,
  ).join("\n");

  return `${BANNER}import { createElement } from "react";\nimport type { SectionConfig } from "./engine";\nimport {\n  bindings,\n  components,\n  predicates,\n  runApply,\n  sections,\n} from "./registry.runtime";\n\nexport const SECTION_CONFIGS: Record<string, SectionConfig> = {\n${entries}\n};\n`;
}

// ----- main -----

function format(files: string[]): void {
  const bin = join(REPO_ROOT, "node_modules/.bin/biome");
  try {
    execFileSync(bin, ["check", "--write", ...files], {
      cwd: REPO_ROOT,
      stdio: "inherit",
    });
  } catch {
    // Biome may exit non-zero when it reports unfixable diagnostics; the
    // files are still written and formatted. Drift check would catch real
    // problems.
  }
}

function main(): void {
  validateManifests(SETTINGS_PREFS, SETTINGS_SECTIONS_MANIFEST);

  const prefsPath = join(SETTINGS_DIR, "prefs.generated.ts");
  const navPath = join(SETTINGS_DIR, "nav.generated.ts");
  const validatorPath = join(SETTINGS_DIR, "validator.generated.ts");
  const sectionsPath = join(DESKTOP_SETTINGS, "sections.generated.ts");

  writeFileSync(prefsPath, generatePrefs());
  writeFileSync(navPath, generateNav());
  writeFileSync(validatorPath, generateValidator());
  writeFileSync(sectionsPath, generateSections());

  format([prefsPath, navPath, validatorPath, sectionsPath]);

  console.log("[generate-settings] wrote 4 files");
}

main();
