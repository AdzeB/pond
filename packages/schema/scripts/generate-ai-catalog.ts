import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Pulls per-model capability + context window from models.dev and writes a
// vendored snapshot the app reads offline. Capability ("can drive the agentic
// loop") is tool calling — the signal for multi-step reasoning; single-shot JSON
// is handled by the SDK + jsonrepair fallback, and models.dev barely populates
// `structured_output`. Context sizes the grounding-facet budget. Maps our
// provider ids onto models.dev's where they differ.
const PROVIDER_MAP: Record<string, string> = {
  openai: "openai",
  anthropic: "anthropic",
  google: "google",
  groq: "groq",
  mistral: "mistral",
  xai: "xai",
  deepseek: "deepseek",
  openrouter: "openrouter",
  together: "togetherai",
  perplexity: "perplexity",
};

interface CatalogModel {
  tool_call?: boolean;
  limit?: { context?: number };
}
interface CatalogProvider {
  models: Record<string, CatalogModel>;
}

const SOURCE = "https://models.dev/api.json";

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`models.dev fetch failed: ${res.status}`);
const catalog = (await res.json()) as Record<string, CatalogProvider>;

let modelCount = 0;
const blocks = Object.entries(PROVIDER_MAP)
  .map(([ourId, mdId]) => {
    const models = catalog[mdId]?.models ?? {};
    const rows = Object.entries(models)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([id, m]) => {
        modelCount += 1;
        const agent = Boolean(m.tool_call);
        const context = m.limit?.context ?? 0;
        return `    ${JSON.stringify(id)}: { agent: ${agent}, context: ${context} },`;
      })
      .join("\n");
    return `  ${ourId}: {\n${rows}\n  },`;
  })
  .join("\n");

const date = new Date().toISOString().slice(0, 10);
const out = `// Generated by \`pnpm --filter @pond/schema generate:ai-catalog\`. Do not edit by hand.
// Source: ${SOURCE} (${date})
//
// Per-model capability and context window. \`agent\` is models.dev's tool_call
// flag (the bar for the multi-step agentic loop); \`context\` is the context
// window in tokens. Providers with no models.dev entry (bundled, ollama,
// lmstudio, custom) are handled by fallbacks in ai-capabilities.ts.

export interface AiModelInfo {
  agent: boolean;
  context: number;
}

export const AI_MODEL_CATALOG: Record<string, Record<string, AiModelInfo>> = {
${blocks}
};
`;

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "src", "ai-catalog.generated.ts");
writeFileSync(outPath, out);
console.log(`wrote ${outPath} (${modelCount} models)`);
