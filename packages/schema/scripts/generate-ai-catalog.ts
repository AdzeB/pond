import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { AI_PROVIDERS, type AiProviderId } from "../src/ai-providers.ts";

/**
 * Pulls per-model capability and context window from models.dev into a vendored snapshot the app reads offline.
 * Agent capability keys off tool calling; models.dev barely populates `structured_output`, so that flag is unused.
 */
const PROVIDER_MAP: Record<string, string> = {
  openai: "openai",
  anthropic: "anthropic",
  google: "google",
  groq: "groq",
  mistral: "mistral",
  xai: "xai",
  deepseek: "deepseek",
  openrouter: "openrouter",
  together: "togetherai",
  perplexity: "perplexity",
};

interface CatalogModel {
  name?: string;
  tool_call?: boolean;
  limit?: { context?: number };
}
interface CatalogProvider {
  models: Record<string, CatalogModel>;
}

const SOURCE = "https://models.dev/api.json";

/** OpenRouter's value here is labs with no native section; the rest are reachable directly. */
const OPENROUTER_PREFIXES = ["meta-llama/", "qwen/", "moonshotai/", "z-ai/"];

/** Dated release suffixes: 2024-05-13, 20251101, and Mistral's YYMM style (2411). */
const DATE_SUFFIX = /-(20\d{2}-\d{2}-\d{2}|20\d{6}|2\d{3})$/;

/** Specialised variants (coding, audio, safety, research) that make no sense for compiling library searches. */
const SPECIALISED =
  /codex|coder|devstral|audio|voxtral|deep-research|guard|transcribe|realtime|tts|whisper|embed|moderation|image|:free|:extended|:nitro/i;

/**
 * The picker free-types any id, so the vendored catalog only needs models a user
 * would plausibly choose: tool-calling chat models (the search compiler's bar),
 * minus dated snapshots that duplicate a rolling alias.
 */
function keep(
  ourId: string,
  id: string,
  m: CatalogModel,
  all: Set<string>,
): boolean {
  if (id === AI_PROVIDERS[ourId as AiProviderId]?.defaultModel) return true;
  if (!m.tool_call) return false;
  if (!m.limit?.context) return false;
  if (SPECIALISED.test(id)) return false;
  const dated = id.match(DATE_SUFFIX);
  if (dated) {
    const base = id.slice(0, -(dated[1].length + 1));
    if (all.has(base) || all.has(`${base}-latest`)) return false;
  }
  if (ourId === "openrouter") {
    return OPENROUTER_PREFIXES.some((p) => id.startsWith(p));
  }
  return true;
}

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`models.dev fetch failed: ${res.status}`);
const catalog = (await res.json()) as Record<string, CatalogProvider>;

let modelCount = 0;
const blocks = Object.entries(PROVIDER_MAP)
  .map(([ourId, mdId]) => {
    const models = catalog[mdId]?.models ?? {};
    const all = new Set(Object.keys(models));
    const rows = Object.entries(models)
      .filter(([id, m]) => keep(ourId, id, m, all))
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([id, m]) => {
        modelCount += 1;
        const name = m.name?.trim() || id;
        const agent = Boolean(m.tool_call);
        const context = m.limit?.context ?? 0;
        return `    ${JSON.stringify(id)}: { name: ${JSON.stringify(name)}, agent: ${agent}, context: ${context} },`;
      })
      .join("\n");
    return `  ${ourId}: {\n${rows}\n  },`;
  })
  .join("\n");

const date = new Date().toISOString().slice(0, 10);
const out = `// Generated by \`pnpm --filter @pond/schema generate:ai-catalog\`. Do not edit by hand.
// Source: ${SOURCE} (${date})
//
// Per-model display name, capability, and context window. \`name\` is models.dev's
// human-readable label; \`agent\` is its tool_call flag (the bar for the multi-step
// agentic loop); \`context\` is the context window in tokens. Providers with no
// models.dev entry (bundled, ollama, lmstudio, custom) are handled by fallbacks
// in ai-capabilities.ts.

export interface AiModelInfo {
  name: string;
  agent: boolean;
  context: number;
}

export const AI_MODEL_CATALOG: Record<string, Record<string, AiModelInfo>> = {
${blocks}
};
`;

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "src", "ai-catalog.generated.ts");
writeFileSync(outPath, out);
console.log(`wrote ${outPath} (${modelCount} models)`);
